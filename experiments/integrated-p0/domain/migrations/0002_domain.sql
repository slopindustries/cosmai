-- 0002 — the domain tables of DP-008: registered sources, cursors, Raw, snapshots.
--
-- This file lives under `domain/migrations/` rather than beside `0001`, and the
-- reason is a test rather than taste: `tests/environment/test_p0a_boundary_guard.py`
-- scans `platform_core/` for domain vocabulary **including its .sql files**, so a
-- migration creating `source` or `raw_item` inside `platform_core/db/migrations/`
-- fails the build. The applier already takes a directory
-- (`platform_core.db.migrate.apply_migrations(..., directory=...)`), so nothing had
-- to be added to make two directories work. Version stems are unique across both,
-- because `schema_migrations.version` is a primary key over the filename stem.
--
-- Three conventions are inherited from `0001` deliberately, so both files read alike:
-- every timestamp is `timestamptz` generated by the database, enumerated columns are
-- `text` with a CHECK rather than a PostgreSQL enum, and every constraint is named
-- after the invariant it holds rather than after its columns.
--
-- What is NOT here, and why:
--
--   * **No install table.** DP-008 D8: the add-on directory is the installed set and
--     this schema records what add-ons *did*, never which ones exist. A table of
--     installed add-ons would be a second truth that can drift from the filesystem.
--   * **No UPDATE/DELETE trigger on the Raw tables.** `docs/project-state.md` §4
--     requires Raw to be "logically append-only", and a trigger would be stronger
--     than that. It was considered and declined on 2026-08-18: DP-005 gives every P0
--     artifact a disposition, one of which is `DELETE_AFTER_EVIDENCE_CAPTURE`, and a
--     trigger forbidding deletion would have to be worked around to honour it.
--     Append-only is held by the application having no statement that rewrites Raw.
--   * **No answer to OQ-004.** The snapshot tables below are the smallest thing that
--     supports `read_snapshot` and tamper detection. Selection semantics and
--     backend-independent snapshot identity remain that question's to settle.

-- ---------------------------------------------------------------------------
-- source — a registered source, and the operator's approved configuration for it.
-- ---------------------------------------------------------------------------
--
-- `docs/conventions/p0-security.md` requires that a dashboard or job payload select
-- a registered `source_id` rather than an arbitrary URL. This table is what
-- "registered" means. Before DP-008 the row was named in three documents and
-- described in none.

create table source (
  -- Text rather than uuid: an operator types it, it appears in a job payload, and
  -- it is half of the `credential_ref` naming convention in secret-setup.md. A
  -- surrogate key would put a second identifier beside the one already in use.
  source_id             text        primary key,

  -- Which add-on runs this source, and which version of it. `addon_id` is the
  -- manifest's own `[addon].id`; the handler the platform dispatches on is derived
  -- from it, so this column and `job.handler` cannot disagree.
  addon_id              text        not null,
  addon_version         text        not null,
  kind                  text        not null,

  -- The operator's approved configuration. **Non-secret by construction**:
  -- `addon_api.validate_config` refuses a field the manifest marked `secret`, so a
  -- token cannot arrive here through the ordinary path. `credential_ref` below is
  -- the only credential-shaped thing this row holds.
  config                jsonb       not null default '{}'::jsonb,
  config_schema_version text        not null,

  -- The secret store's key **name**, never a value (secret-setup.md invariant 3).
  credential_ref        text,

  -- Platform-owned: allowed scheme, host, port, path prefixes, and per-source
  -- limits. Written from the manifest's `[declares]` block only after an operator
  -- approves it, which is what makes a declaration a grant (DP-008 D4). An add-on
  -- never reads or writes this column.
  outbound_profile      jsonb,

  data_class            text        not null default 'local',
  enabled               boolean     not null default true,
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now(),

  constraint source_kind_is_known
    check (kind in ('collector', 'importer', 'normalizer')),

  -- data-handling.md's three classes. `private` is accepted so that a source can be
  -- recorded as one; whether anything may process it is that document's rule and not
  -- this table's.
  constraint source_data_class_is_known
    check (data_class in ('public', 'local', 'private')),

  -- DP-008 D6, enforced by the database rather than by the code that writes rows.
  -- `secret-setup.md` states that `credential_ref` is exactly a key name and that
  -- the naming convention is COSMA_SRC_<SOURCE_ID>_<PURPOSE>; this turns that
  -- sentence into a constraint. A real token pasted into this column does not match
  -- the pattern, so the mistake the invariant is about becomes structurally hard
  -- instead of merely forbidden. It is not a secrecy mechanism — it is a shape
  -- check, and a value that happened to look like a key name would still pass.
  constraint source_credential_ref_is_a_key_name
    check (credential_ref is null or credential_ref ~ '^COSMA_SRC_[A-Z0-9_]+$'),

  -- DP-008 D4's asymmetry, held where it cannot be bypassed. `addon_api`'s manifest
  -- parser already refuses a normalizer that *declares* a host or a credential;
  -- this refuses a normalizer *source* that was granted one. The two checks are the
  -- same rule at the two different moments it can be broken.
  constraint source_normalizer_reaches_nothing_outside_its_snapshot
    check (
      kind <> 'normalizer'
      or (outbound_profile is null and credential_ref is null)
    )
);

create index source_by_addon on source (addon_id);

-- ---------------------------------------------------------------------------
-- source_cursor — where a collector or importer stopped.
-- ---------------------------------------------------------------------------
--
-- The gap DP-008 was written to close. With the collector as platform code, "where
-- did I stop" came from the job payload; that does not survive an operator-installed
-- component, and cursors appeared nowhere in the record except as an illustration of
-- how to label a claim.

create table source_cursor (
  source_id  text        not null references source (source_id),

  -- An add-on names its own streams. The platform does not interpret the name and
  -- does not require it to mean anything; `[declares].streams` is what an operator
  -- sees, not a constraint enforced here.
  stream     text        not null,

  -- **Opaque to the platform.** Whatever the add-on last wrote and will be handed
  -- back. Giving this a schema would put source-specific pagination semantics in the
  -- platform, which is the coupling the add-on layer removes.
  cursor     jsonb       not null,

  -- Which attempt advanced it. This is the audit half of the atomicity requirement:
  -- the cursor's value and the attempt that produced it are written in one
  -- transaction, so a cursor can always be traced to the Raw it accompanies.
  updated_by_attempt uuid not null references job_attempt (id),
  updated_at timestamptz not null default now(),

  primary key (source_id, stream)
);

-- ---------------------------------------------------------------------------
-- raw_envelope — the lossless original, recorded before an add-on interprets it.
-- ---------------------------------------------------------------------------
--
-- `docs/project-state.md` §4: Raw preserves the original payload and its provenance.
-- The envelope is written by the platform's own `fetch`/`open_input`, not by the
-- add-on, which is what makes losslessness independent of add-on quality: an add-on
-- that carves a response badly has produced bad items over a preserved original
-- rather than lost the original.

create table raw_envelope (
  id             uuid        primary key,
  source_id      text        not null references source (source_id),
  job_id         uuid        not null references job (id),
  attempt_id     uuid        not null references job_attempt (id),

  -- Provenance (DP-008 D8). Recorded per envelope rather than read from `source`,
  -- because the source row's `addon_version` moves when an add-on is upgraded and
  -- this must keep saying what actually produced these bytes.
  addon_id       text        not null,
  addon_version  text        not null,

  -- For a collector: the endpoint name the add-on asked for and the platform
  -- resolved. Null for an importer, which asked for a registered input instead.
  endpoint_ref   text,
  input_ref      text,

  -- What was asked and what came back. `request_summary` and `response_headers`
  -- carry no Authorization, Cookie, or provider-protected header: p0-security.md
  -- requires them stripped, and they are stripped before reaching this table rather
  -- than on the way out of it.
  request_summary   jsonb,
  status            integer,
  response_headers  jsonb,

  body           bytea       not null,
  body_sha256    text        not null,
  content_type   text,
  retrieved_at   timestamptz not null default now(),

  constraint raw_envelope_digest_is_a_sha256
    check (body_sha256 ~ '^[0-9a-f]{64}$'),

  -- A collector envelope names an endpoint; an importer envelope names an input.
  -- Exactly one, because an envelope that named both would leave its own provenance
  -- ambiguous, and one that named neither could not be traced to a request at all.
  constraint raw_envelope_names_one_origin
    check ((endpoint_ref is null) <> (input_ref is null))
);

create index raw_envelope_by_source on raw_envelope (source_id, retrieved_at);
create index raw_envelope_by_attempt on raw_envelope (attempt_id);

-- ---------------------------------------------------------------------------
-- raw_item — what the add-on extracted from an envelope.
-- ---------------------------------------------------------------------------

create table raw_item (
  id           uuid        primary key,
  envelope_id  uuid        not null references raw_envelope (id),

  -- Denormalised from the envelope so that "every item of this source" does not
  -- require a join. Kept honest by the constraint below rather than by convention.
  source_id    text        not null references source (source_id),

  -- Identity **within one source**, chosen by the add-on. Deliberately not unique:
  -- what duplicate and changed-content policy this feeds is an open P0-B contract
  -- question, and a unique index here would answer it silently. The index is for
  -- lookup only.
  item_key     text        not null,

  payload      bytea       not null,
  content_type text        not null,
  notes        jsonb       not null default '{}'::jsonb,
  emitted_at   timestamptz not null default now()
);

create index raw_item_by_source_key on raw_item (source_id, item_key);
create index raw_item_by_envelope on raw_item (envelope_id);

-- ---------------------------------------------------------------------------
-- snapshot / snapshot_item — a sealed, hash-verifiable normalizer input.
-- ---------------------------------------------------------------------------
--
-- `docs/project-state.md` §4: a normalization run consumes a sealed, materialized,
-- hash-verifiable input snapshot. This is the **smallest** shape that supports
-- `read_snapshot` and tamper detection, and it is explicitly **not** OQ-004's
-- answer: that question also asks what a selection means and how a snapshot's
-- identity survives a change of storage backend, and neither is settled here.

create table snapshot (
  id                 uuid        primary key,
  source_id          text        not null references source (source_id),

  -- Materialized item count and the digest over the manifest of member digests.
  -- Tamper detection compares a recomputed manifest digest against this value, so
  -- altering an item's bytes is detectable without re-reading every item's own row.
  item_count         integer     not null,
  manifest_sha256    text        not null,

  -- Prose, not a query. What was selected and why, for a human reading a run
  -- afterwards. A machine-readable selection is part of what OQ-004 must decide.
  selection          jsonb       not null default '{}'::jsonb,

  -- Sealed means closed to further members. A run may only consume a sealed
  -- snapshot; the partial index below is what makes "sealed" checkable rather than
  -- a convention.
  sealed_at          timestamptz,
  created_at         timestamptz not null default now(),

  constraint snapshot_manifest_digest_is_a_sha256
    check (manifest_sha256 ~ '^[0-9a-f]{64}$'),
  constraint snapshot_item_count_is_not_negative
    check (item_count >= 0)
);

create index snapshot_sealed on snapshot (source_id, sealed_at) where sealed_at is not null;

create table snapshot_item (
  snapshot_id  uuid        not null references snapshot (id),

  -- Position within the snapshot. Part of the primary key because determinism is
  -- required of a normalizer (OQ-003: byte-identical output from one snapshot), and
  -- an unordered input cannot support that — two runs would see the same items in
  -- two orders.
  ordinal      integer     not null,

  item_key     text        not null,
  payload      bytea       not null,
  content_type text        not null,
  payload_sha256 text      not null,

  primary key (snapshot_id, ordinal),

  constraint snapshot_item_digest_is_a_sha256
    check (payload_sha256 ~ '^[0-9a-f]{64}$'),
  constraint snapshot_item_ordinal_is_zero_based
    check (ordinal >= 0)
);

-- One member per key within a snapshot. Unlike `raw_item`, where duplicate policy is
-- an open question, a sealed input with the same key twice would make a normalizer's
-- output depend on which one it read last — which is exactly the determinism
-- OQ-003 requires.
create unique index snapshot_item_one_per_key on snapshot_item (snapshot_id, item_key);
